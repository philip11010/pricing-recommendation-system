def refuse_duplicate_addresses() -> None:
    """
    Stop before the index fails, naming what has to be decided first.

    Two accounts on the same address in different capitals are two accounts,
    and which one keeps it is a question about people rather than about
    schemas.
    """
    rows = op.get_bind().execute(DUPLICATE_EMAILS).fetchall()
    if not rows:
        return
    raise RuntimeError(
        f"{len(rows)} email address(es) belong to more than one mentor once "
        f"capitals are ignored, and this migration adds a unique index on the "
        f"lowercased address. Decide which account keeps each address before "
        f"migrating. They are the rows returned by:\n"
        f"  SELECT lower(email), count(*) FROM mentors GROUP BY lower(email) "
        f"HAVING count(*) > 1;"
    )


